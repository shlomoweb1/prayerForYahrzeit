#!/usr/bin/env node
/* global CSSRule */
/**
 * Diagnostic only — Folio itself never sees this. Given a captured HTML
 * payload (the same string renderSheetHTML.tsx hands to Folio), report
 * which CSS properties are actually in play, matched against Folio's own
 * declared support surface (go-html-to-pdf's html/css_props.go registry,
 * via its generated docs/CSS_SUPPORT.md), broken down per element.
 *
 * Usage:
 *   node report-css-coverage.mjs <path-to-html> [--support <path-to-CSS_SUPPORT.md>] [--json out.json]
 *
 * Defaults --support to the sibling go-html-to-pdf checkout's generated
 * doc, since that file is regenerated by `go generate ./html/...` and is
 * the single source of truth — this script never hand-maintains its own
 * copy of "what Folio supports".
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { JSDOM } from 'jsdom'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseSupportRegistry, classify } from './support-registry.mjs'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

function parseArgs(argv) {
  const args = { html: null, support: null, json: null }
  const rest = [...argv]
  args.html = rest.shift()
  while (rest.length) {
    const flag = rest.shift()
    if (flag === '--support') args.support = rest.shift()
    else if (flag === '--json') args.json = rest.shift()
    else throw new Error(`unknown arg: ${flag}`)
  }
  return args
}

const DEFAULT_SUPPORT_MD = path.resolve(
  __dirname,
  '../../../../tziyun-berega/go-html-to-pdf/docs/CSS_SUPPORT.md',
)

/** Walks a CSSStyleSheet's rules (recursing into @media/@supports) yielding {selectorText, declarations}. */
function* walkRules(sheet) {
  for (const rule of sheet.cssRules) {
    if (rule.type === CSSRule.STYLE_RULE) {
      const declarations = []
      for (let i = 0; i < rule.style.length; i += 1) {
        const prop = rule.style[i]
        declarations.push([prop, rule.style.getPropertyValue(prop)])
      }
      yield { selectorText: rule.selectorText, declarations }
    } else if (rule.cssRules) {
      yield* walkRules(rule)
    }
  }
}

function shortPath(el) {
  const parts = []
  let node = el
  while (node && node.tagName) {
    let label = node.tagName.toLowerCase()
    const dataAttr = ['data-section', 'data-content', 'data-type', 'data-page'].find((a) =>
      node.hasAttribute(a),
    )
    if (dataAttr) label += `[${dataAttr}="${node.getAttribute(dataAttr)}"]`
    parts.unshift(label)
    node = node.parentElement
    if (parts.length >= 6) {
      parts.unshift('…')
      break
    }
  }
  return parts.join(' > ')
}

function buildReport(html, registry) {
  const dom = new JSDOM(html)
  const { document } = dom.window
  const CSSRuleCtor = dom.window.CSSRule
  globalThis.CSSRule = CSSRuleCtor // walkRules references the global CSSRule constants

  // Folio only ever draws body content — `head`/`meta`/`title`/`style`/
  // `script`/`link` never reach its renderer, so a universal-selector reset
  // (Tailwind preflight's `*,::before,::after{...}`) matching them is noise,
  // not a real coverage gap.
  const allElements = Array.from(document.body.querySelectorAll('*'))

  // property -> classification (computed once per unique property name)
  const propClassCache = new Map()
  const classifyCached = (prop) => {
    if (!propClassCache.has(prop)) propClassCache.set(prop, classify(prop, registry))
    return propClassCache.get(prop)
  }

  // Gather stylesheet rules once.
  const rules = []
  for (const sheet of document.styleSheets) {
    try {
      for (const r of walkRules(sheet)) rules.push(r)
    } catch {
      // Selector jsdom can't parse (e.g. ::before) — declarations still get
      // recorded against a synthetic "(pseudo-element)" bucket below.
    }
  }

  const perElement = []
  const unsupportedIndex = new Map() // prop -> Set of element paths

  for (const el of allElements) {
    const used = new Map() // prop -> value (last writer wins, mirrors cascade order roughly)

    for (const { selectorText, declarations } of rules) {
      let matches
      try {
        matches = el.matches(selectorText)
      } catch {
        continue // pseudo-element or selector jsdom doesn't support matching on a real element
      }
      if (!matches) continue
      for (const [prop, value] of declarations) used.set(prop, value)
    }

    const inlineStyle = el.getAttribute('style')
    if (inlineStyle) {
      for (const decl of inlineStyle.split(';')) {
        const [prop, ...rest] = decl.split(':')
        if (!prop || !rest.length) continue
        used.set(prop.trim(), rest.join(':').trim())
      }
    }

    if (used.size === 0) continue

    const propReport = []
    for (const [prop, value] of used) {
      if (prop.startsWith('--')) continue // custom property, already resolved upstream — not Folio's concern
      const cls = classifyCached(prop)
      propReport.push({ property: prop, value, ...cls })
      if (cls.status === 'unsupported') {
        if (!unsupportedIndex.has(prop)) unsupportedIndex.set(prop, new Set())
        unsupportedIndex.get(prop).add(shortPath(el))
      }
    }

    perElement.push({
      path: shortPath(el),
      properties: propReport,
    })
  }

  // Also record properties declared only inside ::before/::after rules,
  // which never match a real element via .matches() but are still real
  // CSS Folio's pseudo-content path (or lack thereof) needs to handle.
  const pseudoOnly = []
  for (const sheet of document.styleSheets) {
    try {
      for (const rule of sheet.cssRules) {
        if (rule.type === CSSRuleCtor.STYLE_RULE && /::(before|after)/.test(rule.selectorText)) {
          for (let i = 0; i < rule.style.length; i += 1) {
            const prop = rule.style[i]
            if (prop.startsWith('--')) continue
            pseudoOnly.push({
              selector: rule.selectorText,
              property: prop,
              value: rule.style.getPropertyValue(prop),
              ...classifyCached(prop),
            })
          }
        }
      }
    } catch {
      // ignore stylesheets jsdom couldn't parse at all
    }
  }

  const summary = {
    totalElementsWithStyle: perElement.length,
    uniquePropertiesUsed: new Set(perElement.flatMap((e) => e.properties.map((p) => p.property)))
      .size,
    unsupported: Array.from(unsupportedIndex.entries()).map(([property, paths]) => ({
      property,
      occurrences: paths.size,
      examplePaths: Array.from(paths).slice(0, 5),
    })),
  }

  return { summary, pseudoOnly, perElement }
}

function printChecklist(report) {
  const { summary, pseudoOnly } = report
  console.log(`\nCSS coverage report`)
  console.log(`  Elements with any declared style: ${summary.totalElementsWithStyle}`)
  console.log(`  Unique CSS properties in use:      ${summary.uniquePropertiesUsed}`)
  if (summary.unsupported.length === 0) {
    console.log(`\n✓ Every property in use is in Folio's CSS_SUPPORT.md registry.`)
  } else {
    console.log(
      `\n✗ ${summary.unsupported.length} propert${summary.unsupported.length === 1 ? 'y' : 'ies'} in use are NOT in Folio's registry (silently ignored at render time):\n`,
    )
    for (const u of summary.unsupported.sort((a, b) => b.occurrences - a.occurrences)) {
      console.log(`  - ${u.property}  (${u.occurrences} element${u.occurrences === 1 ? '' : 's'})`)
      for (const p of u.examplePaths) console.log(`      e.g. ${p}`)
    }
  }
  if (pseudoOnly.length) {
    console.log(`\n::before/::after declarations (not matchable against real elements):`)
    for (const p of pseudoOnly) {
      console.log(`  - ${p.selector} { ${p.property}: ${p.value} }  [${p.status}]`)
    }
  }
}

const args = parseArgs(process.argv.slice(2))
if (!args.html) {
  console.error('usage: node report-css-coverage.mjs <path-to-html> [--support <CSS_SUPPORT.md>] [--json out.json]')
  process.exit(1)
}

const supportPath = args.support ?? DEFAULT_SUPPORT_MD
const registry = parseSupportRegistry(supportPath)
const html = readFileSync(args.html, 'utf8')
const report = buildReport(html, registry)

printChecklist(report)

if (args.json) {
  writeFileSync(args.json, JSON.stringify(report, null, 2))
  console.log(`\nFull per-element report written to ${args.json}`)
}
